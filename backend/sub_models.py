from pydantic import BaseModel, Field
from sqlalchemy import table
from sqlmodel import SQLModel, Field

class UserData(SQLModel):
    cyber_twin_response: str = Field(default=None, description = "The response generated by the Cyber Twin model based on the users input.")
    risk_level: str = Field(default=None, description = "The risk level associated with the users input, categorized into low, medium, or high.")
    suggested_fix: str = Field(default=None, description = "The suggested fix or recommendation provided by the Cyber Twin model to mitigate any identified risks.")
    locations: list[Location] = Field(default_factory=list,description = "The extracted locations from the users input, categorized into frequent and temporary locations.")
    relationships: list[Relations] = Field(default_factory=list, description = "The extracted relationships from the users input, categorized into family, friends, dating, work, and other.")
    assets: list[Assets] = Field(default_factory=list, description = "The extracted assets from the users input, which can include valuable items or possessions.")
    schedule: list[Schedule] = Field(default_factory=list, description = "The extracted schedule from the users input, which can include events, meetings, or activities.")

class Location(SQLModel, table=True):
    name: str = Field(default=None, primary_key=True, description = "The extracted name of the place, landmark, business, or city.")
    granularity: str = Field(description="How specific the revealed location is.")
    is_frequent_spot: bool = Field(default=False, description="True if the place is users regular destination to visit " \
    "eg. home, work, gym etc.")

class Relations(SQLModel, table=True):
    name: str = Field(default=None, primary_key=True, description = "The extracted name of the person, pet, or entity.")
    type: str = Field(description="Categorize type of the relations based on the " \
    "given categories: [family, friends, dating, work, other]")

class Assets(SQLModel, table=True):
    name: str = Field(default=None, primary_key=True, description = "The extracted name of a asset / a thing")
    is_valuable: bool = Field(default=False, description = "True if it is something the los of which will be a major problem")

class Schedule(SQLModel, table=True):
    time_frame: str = Field(default=None, primary_key=True, description = "The extracted time frame of the event, meeting, or activity.")
    time_category: str = Field(description="Categorize the time frame based on the given categories: [PAST, FUTURE, ONGOING]")
    is_away_from_home: bool = Field(default=False, description="True if the user is away from home for a period of time, e.g. on vacation or business trip")
    is_important_event: bool = Field(default=False, description="True if the user has an important event or meeting scheduled")


